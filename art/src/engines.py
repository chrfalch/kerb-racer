def loudness(x):
    """Perceived level (dB): a high-pass and a presence lift, roughly K-weighting."""
    y = sosfilt(butter(2, 100, "high", fs=SR, output="sos"), x)
    y = y + 0.58 * sosfilt(butter(1, 1500, "high", fs=SR, output="sos"), y)
    return 10 * np.log10(np.mean(y**2) + 1e-12)


def target(rpm, on):
    """The loudness a loop is levelled to: the recorded bank's this replaces,
    which the mix in sound.rs was tuned against, 8 dB from idle to the
    limiter. Coasting sits 3 dB under pulling."""
    x = np.log(rpm / GRID[0]) / np.log(GRID[-1] / GRID[0])
    return -22.0 + 8.0 * x - (0.0 if on else 3.0)


def peak(hz, q, db):
    """A resonant peak (RBJ peaking biquad) as one sos row."""
    a, w = 10 ** (db / 40), 2 * np.pi * hz / SR
    alpha = np.sin(w) / (2 * q)
    b = [1 + alpha * a, -2 * np.cos(w), 1 - alpha * a]
    d = [1 + alpha / a, -2 * np.cos(w), 1 - alpha / a]
    return np.array(b + d) / d[0]


def low_shelf(hz, db):
    """A low shelf (RBJ, slope 1) as one sos row."""
    a, w = 10 ** (db / 40), 2 * np.pi * hz / SR
    alpha = np.sin(w) / np.sqrt(2)
    c, s = np.cos(w), 2 * np.sqrt(a) * alpha
    b = [a * ((a + 1) - (a - 1) * c + s), 2 * a * ((a - 1) - (a + 1) * c), a * ((a + 1) - (a - 1) * c - s)]
    d = [(a + 1) + (a - 1) * c + s, -2 * ((a - 1) + (a + 1) * c), (a + 1) + (a - 1) * c - s]
    return np.array(b + d) / d[0]


def band(x, lo, hi):
    return sosfilt(butter(2, [lo, min(hi, SR * 0.45)], "band", fs=SR, output="sos"), x)


def echo(x, delay_ms, feedback, damping):
    """A pipe's echo: a feedback comb whose loop a one-pole low-pass dulls."""
    d = round(delay_ms * SR / 1000)
    den = np.zeros(d + 1)
    den[0], den[1] = 1.0, -damping
    den[d] -= feedback * (1 - damping)
    return lfilter([1.0, -damping], den, x)


def clip(x, drive, lean):
    """Soft clipping of `x` (about unit peak), lopsided by `lean`: the rasp."""
    return np.tanh(drive * x + lean) - np.tanh(lean)


def rms(x):
    return np.sqrt(np.mean(x**2)) + 1e-12


def pulse(n, at, amp, attack, tau, out):
    """Add one exhaust pulse at sample `at` (fractional) to the periodic `out`:
    it opens over `attack` samples and decays over `tau`."""
    start = int(np.floor(at))
    i = np.arange(start, start + int(8 * tau + 4 * attack) + 2)
    t = np.maximum(i - at, 0.0)
    out[i % n] += amp * (1 - np.exp(-t / attack)) * np.exp(-t / tau)


def edges(e, per_deg):
    """An exhaust pulse's opening and decay (samples): both are crank angles,
    so the pulse sharpens and brightens with the revs."""
    return max(3 * per_deg, 0.15e-3 * SR), max(e.blowdown * per_deg, 0.3e-3 * SR)


def pipes(e, trains):
    """Each bank's pulses echoing down its own pipe, joined."""
    return sum(echo(t, *p) for t, p in zip(trains, e.pipes))


def silencer(e, x, rpm):
    """The silencer and tailpipe's resonances; the silencer swallows the top at
    low revs and lets more through as they rise."""
    x = sosfilt(np.array([peak(*p) for p in e.peaks]), x)
    return sosfilt(butter(2, 1200 * (rpm / GRID[0]) ** 0.9, "low", fs=SR, output="sos"), x)


def bump(n, cycles, angle, width):
    """Over a loop of `cycles` engine cycles, a sine-squared bump `width` crank
    degrees wide starting at `angle`, once per cycle."""
    deg = (np.arange(n) * cycles * 720.0 / n - angle) % 720.0
    return np.where(deg < width, np.sin(np.pi * deg / width) ** 2, 0.0)


def render(e, rpm, on):
    """One seamless loop of engine `e` at `rpm`, pulling (`on`) or coasting."""
    cycles = max(1, round(rpm / 120 * LOOP))
    n = round(cycles * 120 / rpm * SR)
    per_deg = n / (cycles * 720.0)
    revs = rpm / GRID[-1]
    rng = np.random.default_rng([e.seed, rpm, on])
    # Each cylinder's own loudness and timing: the same at every rpm and load.
    own = np.random.default_rng(e.seed)
    cyl = len(e.fires)
    loud = 1 + e.spread * own.uniform(-1, 1, cyl)
    late = 6 * e.spread * own.uniform(-1, 1, cyl)
    attack, tau = edges(e, per_deg)
    tau = tau if on else max(0.6 * tau, 0.3e-3 * SR)
    trains = [np.zeros(n) for _ in e.pipes]
    for k in range(cycles):
        for c in range(cyl):
            at = (k * 720 + e.fires[c] + late[c] + rng.normal(0, 1.0)) * per_deg + e.headers[c] * SR / 1000
            train = trains[e.banks[c]]
            if on:
                pulse(n, at, loud[c] * (1 + 0.04 * rng.normal()), attack, tau, train)
                continue
            # Coasting, every cylinder still pumps air; some of them burn a little.
            burn = 0.3 * rng.lognormal(0, 0.7) if rng.random() < 0.7 else 0.0
            pulse(n, at, loud[c] * (0.15 + burn), attack, tau, train)
            if rng.random() < 0.12:
                late_burn = at + rng.uniform(60, 200) * per_deg
                pulse(n, late_burn, 0.25 * rng.random(), attack, 0.15e-3 * SR, train)
    tile = lambda x: np.tile(x, 3)
    exhaust = pipes(e, [tile(t) for t in trains])
    exhaust = clip(exhaust / (3 * rms(exhaust)), e.rasp * (1.0 if on else 0.6), e.lean)
    exhaust = silencer(e, exhaust, rpm)
    exhaust /= rms(exhaust)

    noise = lambda: tile(rng.normal(0, 1, n))
    breathing = sum(bump(n, cycles, f + 360, 180) for f in e.fires) ** 2
    lo, hi, level = e.intake
    roar = band(noise(), lo, hi) * tile(breathing)
    sound = exhaust + level * revs * (revs**0.2 if on else 0.15) * roar / rms(roar)

    ticks = np.zeros(n)
    for k in range(cycles):
        for f in e.fires:
            for valve in (200, 560):
                pulse(n, (k * 720 + f + valve) * per_deg, rng.uniform(0.6, 1.0), 1.0, 0.3e-3 * SR, ticks)
    ticks = band(tile(ticks) * noise(), 2500, 9000)
    sound += e.clatter * (0.4 + 0.6 * revs) * ticks / rms(ticks)

    if e.fan:
        # Whole cycles in the loop, so it stays seamless; louder as it spins up.
        turns = round(e.fan * rpm / 60 * n / SR)
        phase = 2 * np.pi * turns * np.arange(3 * n) / n
        whine = np.sin(phase) + 0.3 * np.sin(2 * phase)
        sound += 0.03 * revs**1.5 * whine / rms(whine)
    if not on:
        hiss = band(noise(), 2000, 6000)
        sound += 0.03 * hiss / rms(hiss)
        sound = sosfilt(low_shelf(180, -6), sound)

    sound = sosfilt(butter(2, 35, "high", fs=SR, output="sos"), sound)
    sound = sosfilt(butter(4, 9000, "low", fs=SR, output="sos"), sound)
    x = sound[2 * n :]
    return x * 10 ** ((target(rpm, on) - loudness(x)) / 20)


def pop(e, rpm, k, ceiling):
    """Overrun pop `k` of engine `e` at `rpm`: two ("pap-pap") or three
    ("brap") over-strong firings, each a little late, through the engine's own
    pipes and silencer, then 100 ms of tail. It peaks at `ceiling`."""
    rng = np.random.default_rng([e.seed, 99, rpm, k])
    per_deg = SR * 120 / rpm / 720
    attack, tau = edges(e, per_deg)
    gap = 720 / len(e.fires)
    order = sorted(range(len(e.fires)), key=lambda c: e.fires[c])
    strengths = (1.0, 0.7) if k == 0 else (1.0, 0.8, 0.55)
    lead = 0.002 * SR
    n = int(lead + (len(strengths) * gap + 40) * per_deg + 0.1 * SR)
    trains = [np.zeros(n) for _ in e.pipes]
    for b, strength in enumerate(strengths):
        c = order[b % len(order)]
        at = lead + (b * gap + rng.uniform(15, 35)) * per_deg + e.headers[c] * SR / 1000
        pulse(n, at, strength * rng.uniform(0.9, 1.1), attack, 1.3 * tau, trains[e.banks[c]])
    x = pipes(e, trains)
    # Over-strong: the clipper takes it 1.6 times past where a loop's peaks sit.
    x = clip(1.6 * x / np.abs(x).max(), e.rasp, e.lean)
    x = silencer(e, x, rpm)
    # A short burst of one-way pulses is also one low shove, a thump under the
    # note that reads as an impact; a loop's steady stream has none. Cut it.
    firing = rpm / 60 * len(e.fires) / 2
    x = sosfilt(butter(4, 0.7 * firing, "high", fs=SR, output="sos"), x)
    fade = int(0.06 * SR)
    x[-fade:] *= np.cos(np.linspace(0, np.pi / 2, fade)) ** 2
    return x * ceiling / np.abs(x).max()


def write(name, x):
    peak_ = np.abs(x).max()
    assert peak_ < 1.0, f"{name} clips at {peak_:.2f}"
    wavfile.write(os.path.join(OUT, f"{name}.wav"), SR, (x * 32767).round().astype(np.int16))


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for e in ENGINES:
        for on in (True, False):
            for rpm in GRID:
                loop = render(e, rpm, on)
                write(f"engine-{e.name}-{'on' if on else 'off'}-{rpm}", loop)
                if on and rpm in POP_RPMS:
                    for k in range(POP_TAKES):
                        write(f"pop-{e.name}-{rpm}-{k}", pop(e, rpm, k, np.abs(loop).max()))
    print(f"pub const ENGINE_RPMS: [u32; {len(GRID)}] = {GRID};")
    print(f"pub const POP_RPMS: [u32; {len(POP_RPMS)}] = {POP_RPMS};")
